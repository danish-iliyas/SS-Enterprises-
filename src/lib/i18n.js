export const normaliseLang = (l) => (l === 'hi' ? 'hi' : 'en');

// t('key', { n: 3 }) → translated string with {placeholders} filled in.
export function makeT(lang) {
  const table = dict[normaliseLang(lang)];
  return (key, vars) => {
    let s = table[key] ?? dict.en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
    return s;
  };
}

// Picks the right language from a { en, hi } object stored in the database.
export const pickLang = (obj, lang) => (obj ? (lang === 'hi' && obj.hi) || obj.en || '' : '');
